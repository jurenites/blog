import assert from 'node:assert/strict';
import {writeFile as write_file} from 'node:fs/promises';
import {chromium} from 'playwright';
const browser_instance=await chromium.launch({headless:true});
const page_instance=await browser_instance.newPage({viewport:{width:1280,height:900}});
await page_instance.addInitScript(()=>localStorage.setItem('jurenites.site-intro',JSON.stringify({loading:true,shown_at:Date.now()})));
await page_instance.goto('http://jurenites.local/',{waitUntil:'domcontentloaded'});
const preview_card=page_instance.locator('.project-case-preview .card');
await preview_card.scrollIntoViewIfNeeded();
await page_instance.waitForFunction(()=>document.querySelector('.project-case-preview video')?.currentTime>0);
await page_instance.waitForFunction(()=>document.querySelectorAll('.project-case-preview video')[1]?.currentTime>0,{},{timeout:20000});
console.log('Natural sequence advanced from list to filter');
await preview_card.hover();
await page_instance.waitForTimeout(600);
assert.equal(await page_instance.locator('.project-case-preview video').nth(1).evaluate(video_element=>video_element.paused),true);
await page_instance.mouse.move(0,0);
await page_instance.waitForFunction(()=>!document.querySelectorAll('.project-case-preview video')[1].paused);
console.log('Hover pauses and leaving resumes');
await preview_card.focus();
console.log('focus outline',await preview_card.evaluate(card_element=>getComputedStyle(card_element).outlineStyle));
await preview_card.press('Enter');
await page_instance.waitForURL('**/portfolio/scatchapp');
console.log('Keyboard link opens Project');
for (const [video_index,video_name] of ['list','filter'].entries()) {
  const video_element=page_instance.locator('.project-detail video').nth(video_index);
  await video_element.evaluate(async video_item=>{if(video_item.readyState<2)await new Promise(resolve_ready=>video_item.addEventListener('loadeddata',resolve_ready,{once:true}));video_item.currentTime=0.25;await new Promise(resolve_seek=>video_item.addEventListener('seeked',resolve_seek,{once:true}));});
  const frame_data=await video_element.evaluate(video_item=>{const frame_canvas=document.createElement('canvas');frame_canvas.width=video_item.videoWidth;frame_canvas.height=video_item.videoHeight;frame_canvas.getContext('2d').drawImage(video_item,0,0);return frame_canvas.toDataURL('image/png').split(',')[1];});
  await write_file(`src/public/assets/images/projects/scatchapp/${video_name}-poster.png`,Buffer.from(frame_data,'base64'));
}
await page_instance.goto('http://jurenites.local/portfolio',{waitUntil:'domcontentloaded'});
const thumbnail_link=page_instance.locator('a.dynamic-thumbnail[href="/portfolio/scatchapp"]');
assert.equal(await thumbnail_link.count(),1);
await thumbnail_link.screenshot({path:'outputs/scatchapp/svg-thumbnail.png'});
await page_instance.emulateMedia({reducedMotion:'reduce'});
await page_instance.goto('http://jurenites.local/',{waitUntil:'domcontentloaded'});
await preview_card.scrollIntoViewIfNeeded();
await page_instance.waitForTimeout(1000);
assert.equal(await page_instance.locator('.project-case-preview video').evaluateAll(video_items=>video_items.every(video_item=>video_item.paused)),true);
await preview_card.screenshot({path:'outputs/scatchapp/reduced-motion.png'});
console.log('Reduced motion stops videos; SVG thumbnail present');
await browser_instance.close();
