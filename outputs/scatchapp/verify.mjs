import { chromium } from 'playwright';
const browser_instance = await chromium.launch({headless:true});
const page_instance = await browser_instance.newPage({viewport:{width:1440,height:1000}});
await page_instance.addInitScript(() => localStorage.setItem('jurenites.site-intro', JSON.stringify({loading:true,shown_at:Date.now()})));
const page_errors=[];
page_instance.on('pageerror',page_error=>page_errors.push(page_error.message));
await page_instance.goto('http://jurenites.local/',{waitUntil:'domcontentloaded'});
await page_instance.waitForFunction(() => !document.documentElement.hasAttribute('data-site-intro'));
await page_instance.locator('.project-case-preview').scrollIntoViewIfNeeded();
await page_instance.waitForTimeout(1600);
console.log('preview',await page_instance.locator('.project-case-preview').evaluate(preview_element=>({text:preview_element.innerText,frames:preview_element.querySelectorAll('[data-screen-frame]').length,videos:[...preview_element.querySelectorAll('video')].map(video_element=>({src:video_element.currentSrc,width:video_element.videoWidth,height:video_element.videoHeight,duration:video_element.duration,time:video_element.currentTime,paused:video_element.paused,error:video_element.error?.message})),markup:preview_element.querySelector('[data-card-phone]')?.outerHTML.slice(0,400)})));
await page_instance.locator('.project-case-preview').screenshot({path:'outputs/scatchapp/home-desktop.png'});
await page_instance.goto('http://jurenites.local/portfolio/scatchapp',{waitUntil:'domcontentloaded'});
await page_instance.waitForFunction(() => !document.documentElement.hasAttribute('data-site-intro'));
await page_instance.waitForTimeout(1200);
console.log('project',await page_instance.locator('.project-detail').innerText());
await page_instance.screenshot({path:'outputs/scatchapp/project-desktop.png',fullPage:true});
await page_instance.setViewportSize({width:390,height:844});
await page_instance.screenshot({path:'outputs/scatchapp/project-mobile.png',fullPage:true});
await page_instance.goto('http://jurenites.local/',{waitUntil:'domcontentloaded'});
await page_instance.waitForFunction(() => !document.documentElement.hasAttribute('data-site-intro'));
await page_instance.locator('.project-case-preview').scrollIntoViewIfNeeded();
await page_instance.locator('.project-case-preview').screenshot({path:'outputs/scatchapp/home-mobile.png'});
console.log('overflow',await page_instance.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'errors',page_errors);
await browser_instance.close();
