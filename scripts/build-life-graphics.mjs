import { mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { TOKEN_VALUES } from '../generated/token/tokens.js';
import { GLIDER_CELLS } from '../src/slice/src/js/game-of-life-engine.js';

const OUTPUT_DIRECTORY = new URL('../src/public/assets/images/game-of-life/', import.meta.url);
const BACKGROUND_COLOR = TOKEN_VALUES['color-palette-full-black'];
const LIVING_COLOR = TOKEN_VALUES['theme-dark-text-primary-default'];
const MUTED_COLOR = TOKEN_VALUES['theme-dark-text-secondary-default'];
const GRID_COLOR = TOKEN_VALUES['theme-dark-border-divider-default'];

function pattern_grid(living_cells, origin_horizontal, origin_vertical, draw_circles = false) {
  const grid_parts = [];
  for (let row_index = 0; row_index < 6; row_index += 1) {
    for (let column_index = 0; column_index < 6; column_index += 1) {
      const cell_horizontal = origin_horizontal + column_index * 24;
      const cell_vertical = origin_vertical + row_index * 24;
      grid_parts.push(`<rect x="${cell_horizontal}" y="${cell_vertical}" width="24" height="24" fill="none" stroke="${GRID_COLOR}"/>`);
    }
  }
  for (const [column_index, row_index] of living_cells) {
    const cell_horizontal = origin_horizontal + column_index * 24;
    const cell_vertical = origin_vertical + row_index * 24;
    grid_parts.push(draw_circles
      ? `<circle cx="${cell_horizontal + 12}" cy="${cell_vertical + 12}" r="9" fill="${LIVING_COLOR}"/>`
      : `<rect x="${cell_horizontal + 3}" y="${cell_vertical + 3}" width="18" height="18" fill="${LIVING_COLOR}"/>`);
  }
  return grid_parts.join('');
}

function text_label(label_text, horizontal_position, vertical_position, is_muted = false) {
  return `<text x="${horizontal_position}" y="${vertical_position}" fill="${is_muted ? MUTED_COLOR : LIVING_COLOR}" font-family="sans-serif" font-size="18">${label_text}</text>`;
}

function svg_document(figure_title, image_height, figure_markup) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 760 ${image_height}" role="img" aria-label="${figure_title}"><!-- Generated by scripts/build-life-graphics.mjs from design tokens and exact Life patterns. --><rect width="760" height="${image_height}" fill="${BACKGROUND_COLOR}"/>${figure_markup}</svg>\n`;
}

const INITIAL_GLIDER = GLIDER_CELLS.map(([column_index, row_index]) => [column_index + 1, row_index + 1]);
const LATER_GLIDER = GLIDER_CELLS.map(([column_index, row_index]) => [column_index + 2, row_index + 2]);
const PATTERN_FIGURE = text_label('BLOCK · unchanged', 32, 38)
  + pattern_grid([[2, 2], [3, 2], [2, 3], [3, 3]], 32, 60)
  + text_label('BLINKER · one generation', 248, 38)
  + pattern_grid([[1, 2], [2, 2], [3, 2]], 248, 60)
  + text_label('→', 415, 140) + pattern_grid([[2, 1], [2, 2], [2, 3]], 464, 60)
  + text_label('GLIDER · generation 0 → generation 4', 32, 258)
  + pattern_grid(INITIAL_GLIDER, 32, 282)
  + text_label('→', 196, 362) + pattern_grid(LATER_GLIDER, 248, 282)
  + text_label('One cell diagonally.', 464, 330, true)
  + text_label('The same rules.', 464, 360, true);
const SHAPE_FIGURE = text_label('SQUARES', 116, 40)
  + pattern_grid(INITIAL_GLIDER, 116, 64)
  + text_label('CIRCLES', 492, 40)
  + pattern_grid(INITIAL_GLIDER, 492, 64, true)
  + text_label('Same cells. Same eight neighbours. Same next generation.', 116, 252, true);

await mkdir(OUTPUT_DIRECTORY, { recursive: true });
await writeFile(new URL('patterns.svg', OUTPUT_DIRECTORY), svg_document('A block, a blinker, and a moving glider', 460, PATTERN_FIGURE));
await writeFile(new URL('squares-and-circles.svg', OUTPUT_DIRECTORY), svg_document('The same glider in squares and circles', 288, SHAPE_FIGURE));
console.log('Built two original, token-derived Life diagrams.');

// Optional raster conversion with an existing Sharp runtime; no global install.
const RASTER_RUNTIME = process.argv[2];
if (RASTER_RUNTIME) {
  const runtime_require = createRequire(RASTER_RUNTIME);
  const sharp_renderer = runtime_require('sharp');
  for (const image_name of ['patterns', 'squares-and-circles']) {
    await sharp_renderer(new URL(`${image_name}.svg`, OUTPUT_DIRECTORY).pathname, { density: 192 })
      .png().toFile(new URL(`${image_name}.png`, OUTPUT_DIRECTORY).pathname);
  }
  console.log('Built PNG counterparts for Drupal Basic HTML.');
}
