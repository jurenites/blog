import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { TOKEN_VALUES } from '../generated/token/tokens.js';

/** Initial HTML estimates share the existing spacing grid; no new tokens. */
export async function write_card_loading_markup(project_directory) {
  const base_gap = Number.parseFloat(TOKEN_VALUES['space-scale-base-gap']);
  const height_estimates = {
    'article-list': base_gap * 20,
    'article-teaser': base_gap * 44,
    'project-card': base_gap * 40,
    'news-list': base_gap * 16,
  };
  const template_source = `{# Generated by scripts/build-card-loading.mjs. Do not edit. #}
{% macro loading_attributes(card_kind) %}
  {% set height_estimates = ${JSON.stringify(height_estimates)} %}
  data-card-loading="{{ card_kind }}" style="min-height:{{ height_estimates[card_kind] }}px"
{% endmacro %}
`;
  await writeFile(resolve(project_directory,
    'web/themes/custom/jurenites_theme/templates/components/card-loading.html.twig'), template_source);
}
