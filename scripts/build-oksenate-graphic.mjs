// Rebuild the editorial score graphic using the project's generated colors.
import { mkdir, writeFile } from "node:fs/promises";
import { TOKEN_RECORDS } from "../generated/token/tokens.js";

function token_color(token_name) {
  const token_record = TOKEN_RECORDS.find((current_record) => current_record.name === token_name);
  if (!token_record) throw new Error(`Missing graphic color: ${token_name}`);
  return token_record.resolved_css_value;
}

const BACKGROUND_COLOR = token_color("theme-dark-surface-background-elevation-level-0");
const TEXT_COLOR = token_color("theme-dark-text-primary-default");
const MUTED_COLOR = token_color("theme-dark-text-secondary-default");
const ACCENT_COLOR = token_color("color-palette-brand-tertiary");
const TRACK_COLOR = token_color("theme-dark-border-divider-default");
const GRAPHIC_DIRECTORY = new URL("../src/public/assets/images/projects/oksenate/", import.meta.url);
const GRAPHIC_MARKUP = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 960 440" role="img" aria-labelledby="graphic-title graphic-description">
<!-- Generated by scripts/build-oksenate-graphic.mjs; colors come from tokens.yaml. -->
<title id="graphic-title">Lighthouse accessibility: 91 to 98</title>
<desc id="graphic-description">Before: 91 out of 100. At release: 98 out of 100. Seven points gained. Historical results from the engagement notes, not a current audit.</desc>
<rect width="960" height="440" rx="16" fill="${BACKGROUND_COLOR}"/>
<g font-family="Arial, sans-serif" text-anchor="middle">
<text x="480" y="56" font-size="22" letter-spacing="3" fill="${MUTED_COLOR}">LIGHTHOUSE · ACCESSIBILITY</text>
<g fill="none" stroke-width="12">
<circle cx="250" cy="222" r="94" stroke="${TRACK_COLOR}"/>
<circle cx="250" cy="222" r="94" stroke="${MUTED_COLOR}" pathLength="100" stroke-dasharray="91 100" transform="rotate(-90 250 222)"/>
<circle cx="710" cy="222" r="94" stroke="${TRACK_COLOR}"/>
<circle cx="710" cy="222" r="94" stroke="${ACCENT_COLOR}" pathLength="100" stroke-dasharray="98 100" transform="rotate(-90 710 222)"/>
</g>
<text x="250" y="244" font-size="72" fill="${TEXT_COLOR}">91</text>
<text x="710" y="244" font-size="72" fill="${TEXT_COLOR}">98</text>
<text x="480" y="217" font-size="38" fill="${ACCENT_COLOR}">+7</text>
<text x="480" y="250" font-size="20" fill="${MUTED_COLOR}">points</text>
<text x="250" y="361" font-size="24" fill="${MUTED_COLOR}">Before</text>
<text x="710" y="361" font-size="24" fill="${TEXT_COLOR}">At release</text>
<text x="480" y="411" font-size="17" fill="${MUTED_COLOR}">Scores out of 100 · Reported release-time results</text>
</g>
</svg>
`;
await mkdir(GRAPHIC_DIRECTORY, { recursive: true });
await writeFile(new URL("lighthouse-accessibility.svg", GRAPHIC_DIRECTORY), GRAPHIC_MARKUP);
